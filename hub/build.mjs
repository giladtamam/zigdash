// Builds hub/zigdash-engine.js (the file the app installs into Zigbee2MQTT)
// from hub/src/engine.js and the Node-RED flows' function bodies, which run
// unchanged inside the Engine. Usage: node hub/build.mjs  (--check: fail if stale)
import fs from 'node:fs';
const root = new URL('../', import.meta.url).pathname;
const body = (flow, name) => fs.readFileSync(`${root}node-red/${flow}/${name}.js`, 'utf8');
const fn = (flow, name) =>
  `function (msg, flow, env, node, Buffer, crypto) {\n${body(flow, name).replace(/^/gm, '      ')}\n    }`;
const FLOWS = {
  alerts: {
    heartbeat: 'zigdash/alerts/bridge/state',
    names: ['ingest', 'restore', 'watch', 'test', 'push', 'result', 'heartbeat'],
    inputs: [
      { topic: 'zigdash/alerts/config', to: 'ingest' },
      { topic: 'zigdash/alerts/state', to: 'restore' },
      { devices: true, to: 'watch' },
      { topic: 'zigdash/alerts/test', to: 'test' },
    ],
    wires: { ingest: [['out']], restore: [[]], watch: [['push'], ['out']], test: [['push']], push: [['http']], result: [['out']], heartbeat: [['out']] },
    httpTo: 'result',
    timers: [{ first: 1000, every: 30000, to: 'heartbeat' }],
  },
  history: {
    heartbeat: 'zigdash/history/bridge/state',
    names: ['ingest', 'restore', 'record', 'tally', 'restoretally', 'tick', 'heartbeat'],
    inputs: [
      { topic: 'zigdash/history/config', to: 'ingest' },
      { topic: 'zigdash/history/+/+/+', to: 'restore' },
      { topic: 'zigdash/history/tally/+/+/+', to: 'restoretally' },
      { devices: true, to: 'record' },
      { devices: true, to: 'tally' },
    ],
    wires: { ingest: [[]], restore: [[]], record: [[]], tally: [[]], restoretally: [[]], tick: [['out']], heartbeat: [['out']] },
    httpTo: null,
    timers: [{ first: 5000, every: 60000, to: 'tick' }, { first: 1000, every: 30000, to: 'heartbeat' }],
  },
};
const out = ['const FLOWS = {'];
for (const [name, d] of Object.entries(FLOWS)) {
  out.push(`  ${name}: {`);
  out.push(`    heartbeat: ${JSON.stringify(d.heartbeat)},`);
  out.push(`    inputs: ${JSON.stringify(d.inputs)},`);
  out.push(`    wires: ${JSON.stringify(d.wires)},`);
  out.push(`    httpTo: ${JSON.stringify(d.httpTo)},`);
  out.push(`    timers: ${JSON.stringify(d.timers)},`);
  out.push('    fns: {');
  for (const n of d.names) out.push(`    ${n}: ${fn(name, n)},`);
  out.push('    },');
  out.push('  },');
}
out.push('};');
const src = fs.readFileSync(`${root}hub/src/engine.js`, 'utf8');
if (!src.includes('/*@FLOWS@*/')) throw new Error('marker missing');
const built = '// GENERATED by hub/build.mjs from hub/src/engine.js and node-red/{alerts,history}/*.js. Do not edit.\n' +
  src.replace('/*@FLOWS@*/', out.join('\n'));
const target = `${root}hub/zigdash-engine.js`;
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== built) { console.error('hub/zigdash-engine.js is stale: run node hub/build.mjs'); process.exit(1); }
  console.log('hub/zigdash-engine.js is up to date');
} else {
  fs.writeFileSync(target, built);
  console.log('wrote hub/zigdash-engine.js', built.length, 'bytes');
}
